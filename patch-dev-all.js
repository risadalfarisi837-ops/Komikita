// dan sembunyikan bottom nav di /dev.   Jalankan dari ~/komikita:   node patch-dev-all.js
const fs = require('fs');
const MARK = 'Dev Tools (khusus role Developer)';
const rd = (f) => fs.readFileSync(f, 'utf8');
const wr = (f, s) => fs.writeFileSync(f, s);
let fail = 0;
const step = (name, fn) => { try { const r = fn(); console.log((r === 'skip' ? 'SKIP  ' : 'OK    ') + name); } catch (e) { fail++; console.log('GAGAL ' + name + ' -> ' + e.message); } };

// 0. pastikan beranda tidak ketimpa file panel Dev
step('cek app/page.tsx (beranda)', () => {
  if (rd('app/page.tsx').includes(MARK)) throw new Error('beranda ketimpa panel Dev, jalankan node restore-home.js dulu');
});

// 1. game Mancing: buang tombol & panel Dev Tools
step('FishingGame.tsx: buang panel Dev Tools', () => {
  const f = 'components/fishing/FishingGame.tsx';
  let s = rd(f);
  if (!s.includes('<DevFab')) return 'skip';
  const imp = "import DevTools, { DevFab, EMPTY_STATS } from './DevTools';";
  if (!s.includes(imp)) throw new Error('baris import DevTools tidak ketemu');
  s = s.replace(imp, "import { EMPTY_STATS } from './DevTools';");
  s = s.replace("  const [devOpen, setDevOpen] = useState(false);\n", '');
  const re = /      \{\/\* Dev Tools \(auto fishing dll\): hanya role Developer \*\/\}\n      \{dev && \(\n[\s\S]*?\n      \)\}\n\n/;
  if (!re.test(s)) throw new Error('blok JSX Dev Tools tidak ketemu');
  s = s.replace(re, '');
  wr(f, s);
});

// 2. halaman Mancing: role Developer tidak lagi mengaktifkan fitur dev di game
step('mancing/page.tsx: matikan mode dev di game', () => {
  const f = 'app/komikstore/mancing/page.tsx';
  let s = rd(f);
  const a = "setIsDev(v.role === 'Developer'); isDevRef.current = v.role === 'Developer';";
  if (!s.includes(a)) return 'skip';
  wr(f, s.replace(a, 'setIsDev(false); isDevRef.current = false;'));
});

// 3. bottom nav disembunyikan di /dev
step('BottomNav.tsx: sembunyikan di /dev', () => {
  const f = 'components/BottomNav.tsx';
  let s = rd(f);
  if (s.includes("startsWith('/dev')")) return 'skip';
  const a = "pathname.startsWith('/komikstore/pet')) return null;";
  if (!s.includes(a)) throw new Error('baris hide nav tidak ketemu');
  wr(f, s.replace(a, "pathname.startsWith('/komikstore/pet') || pathname.startsWith('/dev')) return null;"));
});

